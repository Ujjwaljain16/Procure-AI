"""A deterministic stand-in for the real Gemini API, used for the
replay/mocked evaluation mode when the real API is rate-limited or
unavailable (see docs/architecture_comparison.md for exactly when this
applies).

It exercises the full mechanical pipeline -- tool selection, tool
execution, evidence flow, policy evaluation, and final validation --
identically for Architecture A and B, using a fixed, generic tool-selection
policy (always check employee/budget, catalog, and vendor evidence when the
relevant request fields are present, matching the "prioritize reliability"
baseline guidance from the Architecture A design). It does NOT simulate
genuine model reasoning: its recommendation/rationale/analyst-report text is
templated, not reasoned. This makes it suitable for the deterministic and
safety metrics in the Phase 6 comparison, but explicitly NOT for judging
semantic recommendation quality -- that requires the real API.
"""

from __future__ import annotations

from src.agent.gemini_adapter import ModelTurn, ToolCall
from src.agent.schemas import AgentSynthesis
from src.agent.staged_schemas import AnalystReport


class ReplayGeminiClient:
    def __init__(self, raw_request: dict):
        self._raw = raw_request
        self._turn_index = 0

    def generate_turn(self, contents, tool_specs, system_instruction) -> ModelTurn:
        # Evidence is gathered by the application before any model call, so the
        # stand-in makes no supplemental tool calls.
        return ModelTurn(function_calls=(), text="", raw_content=object())

    def generate_analyst_report(self, contents, system_instruction) -> AnalystReport:
        return AnalystReport(
            request_summary=f"Request for {self._raw.get('product_name') or '(unknown product)'} "
            f"from {self._raw.get('vendor_name') or '(unknown vendor)'}.",
            observations=["Evidence gathered via the standard employee/budget, catalog, and vendor tools."],
            unresolved_questions=[],
            contextual_risks=[],
            evidence_refs=[],
        )

    def generate_structured(self, contents, system_instruction) -> AgentSynthesis:
        return AgentSynthesis(
            recommendation="Route to the reviewers/approvals indicated by the policy evaluation (replay stand-in).",
            rationale="Generated by the deterministic replay client for mechanical pipeline testing, not a real model judgment.",
            evidence_refs=[],
            next_step="Apply the required approvals and address any missing information before proceeding.",
        )

    def build_function_response_content(self, call: ToolCall, result: dict):
        return {"role": "tool", "function_response_for": call.name, "result": result}
